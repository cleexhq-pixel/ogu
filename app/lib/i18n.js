/** @typedef {'ko'|'en'|'id'|'fr'|'pt'} UILang */

export const LANG_CODES = /** @type {const} */ (["ko", "en", "id", "fr", "pt"]);
export const OGU_LANG_KEY = "ogu_lang";

/**
 * @param {string | null | undefined} code
 * @returns {UILang}
 */
export function normalizeLang(code) {
  const c = String(code || "").toLowerCase();
  if (c === "pt-br" || c === "pt_br") return "pt";
  return /** @type {UILang} */ (LANG_CODES.includes(c) ? c : "en");
}

/**
 * @param {string | null | undefined} code
 */
export function isValidLang(code) {
  return LANG_CODES.includes(String(code || "").toLowerCase());
}

/**
 * @param {string | null | undefined} urlLang
 * @param {string | null | undefined} storedLang
 * @returns {UILang}
 */
export function resolveLangFromUrlAndStorage(urlLang, storedLang) {
  if (isValidLang(urlLang)) return normalizeLang(urlLang);
  if (isValidLang(storedLang)) return normalizeLang(storedLang);
  return "en";
}

/**
 * Replace {n}, {day}, etc. in template strings.
 * @param {string} template
 * @param {Record<string, string | number>} vars
 */
function fill(template, vars) {
  let s = template;
  for (const [k, v] of Object.entries(vars)) {
    s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** @param {UILang} lang */
function dict(lang) {
  return STR[lang] || STR.en;
}

/**
 * @param {UILang} lang
 * @param {keyof typeof STR['en']} key
 * @param {Record<string, string | number>} [vars]
 */
export function tx(lang, key, vars) {
  const d = dict(lang);
  let s = d[key];
  if (s == null) s = STR.en[key] ?? key;
  if (vars) s = fill(s, vars);
  return s;
}

